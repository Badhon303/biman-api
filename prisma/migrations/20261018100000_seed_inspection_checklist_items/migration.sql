SELECT gen_random_uuid(), category.id, item.label,
       ROW_NUMBER() OVER (PARTITION BY item.category ORDER BY item.sort_order) - 1
FROM unique_catalog AS item
JOIN inspection_checklist_categories AS category ON category.name = item.category
WHERE NOT EXISTS (
  SELECT 1
  FROM inspection_checklist_items AS existing
  WHERE existing.category_id = category.id
    AND LOWER(existing.label) = LOWER(item.label)
);